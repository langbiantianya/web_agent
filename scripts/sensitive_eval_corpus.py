"""敏感词过滤器的**留出评测语料**（不参与训练）。

## 为什么单独放一个文件

训练语料（:mod:`scripts.sensitive_corpus`）和评测语料必须是**两套**：
训练语料里的每一条都参与过梯度更新，拿它评测等于拿答案对卷，指标只会好看。

这份文件里的句子**从不进入训练集**。它的用途是回答一个具体问题：

> 过滤器在**真实的、无害的中文**上，误杀率是多少？

## 怎么用

```bash
python -m scripts.eval_sensitive            # 评测仓库里的模型
python -m scripts.eval_sensitive --model x.npz
```

## 评测口径

- **误报率（FPR）**：``EVAL_NEGATIVE`` 里被拦下的比例。这是**最要紧**的数字——
  误杀一个正常请求比漏掉一条敏感请求伤得多，用户会直接绕开服务。
- **召回率（TPR）**：``EVAL_POSITIVE`` 里被拦下的比例。
- 两个数**必须一起看**：把阈值往上调，误报率归零、召回率也跟着归零，
  那不叫修好，叫把过滤器关掉。

## 这份语料长什么样

刻意做成「真实用户会发给 LLM 的样子」：有长有短、有口语有书面、有技术有
生活。里面**大量**包含会被「词表式」过滤器误伤的字（人、的、怎么、别人、
情、色、家、到……），但没有一条是真的敏感请求——它们正是模型最容易搞错的
那批。
"""


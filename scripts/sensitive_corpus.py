def build_dataset() -> tuple[list[str], list[int], dict[str, int]]:
    """把四组语料拼成训练集。

    Returns:
        ``(texts, labels, stats)``——文本列表、标签列表（1=敏感）、
        以及每类样本条数。
    """
    texts: list[str] = []
    labels: list[int] = []
    for group in (
        VIOLENCE_POSITIVE,
        PORN_POSITIVE,
        POLITICAL_POSITIVE,
        FRAUD_POSITIVE,
        HATE_POSITIVE,
        INDIRECT_POSITIVE,
    ):
        for t in group:
            texts.append(t)
            labels.append(1)
    for group in (ORDINARY_NEGATIVE, HARD_NEGATIVE):
        for t in group:
            texts.append(t)
            labels.append(0)
    stats = {
        "positive": sum(labels),
        "negative": len(labels) - sum(labels),
        "violence": len(VIOLENCE_POSITIVE),
        "porn": len(PORN_POSITIVE),
        "political": len(POLITICAL_POSITIVE),
        "fraud_privacy": len(FRAUD_POSITIVE),
        "hate": len(HATE_POSITIVE),
        "indirect_positive": len(INDIRECT_POSITIVE),
        "ordinary_negative": len(ORDINARY_NEGATIVE),
        "hard_negative": len(HARD_NEGATIVE),
    }
    return texts, labels, stats


# ---------------------------------------------------------------- 上下文包装
#
# 真实提示词很少是「就一句话」——敏感请求常常夹在一堆正常内容中间
# （「我在写安全科普文章，……顺便教我怎么自制炸药」）。只拿「整句都是敏感内容」
# 的样本去训，模型学到的就是「整句敏感」这一种形态：敏感短语一旦被正常句子
# 稀释，证据占比掉下去，分数就跟着掉，漏检。
#
# 所以训练时给样本加一层正常上下文，把「敏感证据只占一小段」这个形态也喂进去。
# **正负例都要包**：只包正例的话，模型会学成「长文本 = 敏感」，误报直线上升。

EMBED_PREFIXES = [
    "我最近在写一篇安全科普文章，",
    "你好，",
    "帮我看下这个问题：",
    "在讨论犯罪心理的时候有人提到，",
    "作为一个科幻小说的设定，",
    "我在准备明天的汇报，",
    "顺便问一下，",
    "看了你上次的回复，",
]

EMBED_SUFFIXES = [
    "，谢谢。",
    "？",
    "，帮我补充一些细节。",
    "，谢谢你的帮助！",
    "，越详细越好。",
    "，我先谢谢你了。",
    "，麻烦了。",
]


def embed_text(text: str, salt: int = 0) -> str:
    """把一句话包进一段正常上下文里。

    Args:
        text: 原始文本。
        salt: 用来挑前缀/后缀的整数，让同样的输入总是得到同样的包装
            （可复现比随机更重要——否则每次训练的语料都不一样，指标没法比）。

    Returns:
        包装后的长句。
    """
    prefix = EMBED_PREFIXES[salt % len(EMBED_PREFIXES)]
    suffix = EMBED_SUFFIXES[salt % len(EMBED_SUFFIXES)]
    return f"{prefix}{text}{suffix}"
